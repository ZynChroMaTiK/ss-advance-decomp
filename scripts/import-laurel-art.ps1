public static class SsaLaurelImport {
    public static byte[] Raster(Bitmap source,int width,int height,Color[] palette,int[] allowed,bool crop) {
        int left=0,top=0,right=source.Width,bottom=source.Height;
        if(crop) {
            left=source.Width;top=source.Height;right=bottom=0;
            for(int y=0;y<source.Height;y++)for(int x=0;x<source.Width;x++)
                if(source.GetPixel(x,y).A>=128){left=Math.Min(left,x);top=Math.Min(top,y);right=Math.Max(right,x+1);bottom=Math.Max(bottom,y+1);}
        }
        if(right<=left || bottom<=top)throw new Exception("Empty generated artwork");
        double scale=Math.Min((double)width/(right-left),(double)height/(bottom-top));
        double offsetX=(width-(right-left)*scale)/2,offsetY=(height-(bottom-top)*scale)/2;
        byte[] pixels=new byte[width*height];
        for(int y=0;y<height;y++)for(int x=0;x<width;x++) {
            double alpha=0,red=0,green=0,blue=0;
            for(int sy=0;sy<8;sy++)for(int sx=0;sx<8;sx++) {
                int px=(int)Math.Floor(left+(x+(sx+0.5)/8-offsetX)/scale);
                int py=(int)Math.Floor(top+(y+(sy+0.5)/8-offsetY)/scale);
                if(px<left || px>=right || py<top || py>=bottom)continue;
                Color c=source.GetPixel(px,py);alpha+=c.A;
                // Filter in linear light so dark outlines do not drown the gold highlights.
                red+=Math.Pow(c.R/255.0,2.2)*c.A;
                green+=Math.Pow(c.G/255.0,2.2)*c.A;
                blue+=Math.Pow(c.B/255.0,2.2)*c.A;
            }
            if(alpha/64<112)continue;
            red=255*Math.Pow(red/alpha,1/2.2);
            green=255*Math.Pow(green/alpha,1/2.2);
            blue=255*Math.Pow(blue/alpha,1/2.2);
            double best=double.MaxValue;int index=0;
            foreach(int candidate in allowed) {
                Color c=palette[candidate];double dr=red-c.R,dg=green-c.G,db=blue-c.B;
                double distance=dr*dr+dg*dg+db*db;
                if(distance<best){best=distance;index=candidate;}
            }
            pixels[y*width+x]=(byte)index;
        }
        return pixels;
    }
    public static Bitmap Indexed(byte[] pixels,int width,int height,Color[] colors) {
        Bitmap image=new Bitmap(width,height,PixelFormat.Format8bppIndexed);
