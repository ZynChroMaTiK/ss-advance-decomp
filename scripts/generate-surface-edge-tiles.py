"""Bake two-ink floor/ceiling grime tiles; runtime only selects stored texels."""
from pathlib import Path
import math
ROOT = Path(__file__).resolve().parents[1]
def h(n):
    n &= 0xffffffff
    n ^= n >> 16; n = n * 0x7feb352d & 0xffffffff
    n ^= n >> 15; n = n * 0x846ca68b & 0xffffffff
    return n ^ (n >> 16)
def noise(x, y, seed, size):
    ix, iy = int(x // size), int(y // size)
    fx, fy = x / size - ix, y / size - iy
    fx = fx * fx * (3 - 2 * fx); fy = fy * fy * (3 - 2 * fy)
    def at(a,b): return (h(int(seed + a * 1987 + b * 613)) & 65535) / 65535
    return (at(ix,iy)*(1-fx)+at(ix+1,iy)*fx)*(1-fy)+(at(ix,iy+1)*(1-fx)+at(ix+1,iy+1)*fx)*fy
rows = []
for surface in range(2):
    banks = []
    for bank in range(8):
        variants = []
        for joins in range(4):
            tile = []
            for y in range(16):
                row = 0
                for x in range(64):
                    # Identical endpoint profiles/dither for every connected
                    # bank. The first/last eight texels blend into each body.
                    blend = min(1, min(x,63-x)/8)
                    shared = noise(0,y,117+surface*311,5)
                    detail = noise(x,y,117+bank*3571+surface*311,5)
                    width = 6 + 7*(shared*(1-blend)+detail*blend) - surface
                    cap = min(1, (x/12 if not joins&1 else 1), ((63-x)/12 if not joins&2 else 1))
                    feather = max(0,min(1,(width-y)/5))
                    holes = noise(x if blend else 0,y,713+bank*blend*3571+surface*311,4)
                    coverage = feather*cap*(0.32+0.55*holes)
                    # Shared endpoint dither and porous interiors; no new color.
                    salt = 0 if not blend else bank*1999
                    rank = (h((0 if x==63 else x)+y*131+salt+surface*619)&65535)/65535
                    if rank < coverage: row |= 1 << x
                tile.append(row)
            variants.append(tile)
        banks.append(variants)
    rows.append(banks)
out = ['/* Generated by scripts/generate-surface-edge-tiles.py. Two-ink64x16 tiles. */',
       'enum { SURFACE_EDGE_VARIANTS=8, SURFACE_EDGE_WIDTH=64, SURFACE_EDGE_DEPTH=16 };',
       'static const uint64_t surface_edge_tiles[2][8][4][16]={']
for banks in rows:
    out.append(' {')
    for variants in banks:
        out.append('  {')
        for tile in variants:
            out.append('   {'+','.join('UINT64_C(0x%016x)'%r for r in tile)+'},')
        out.append('  },')
    out.append(' },')
out.append('};')
(ROOT/'src/surface_edge_tiles.inc').write_text('\n'.join(out)+'\n')
