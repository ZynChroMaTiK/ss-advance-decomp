param([string]$Source=(Join-Path $PSScriptRoot '../assets/classic-hud/time-strike-reference.png'))
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Drawing
$bitmap=[Drawing.Bitmap]::FromFile([IO.Path]::GetFullPath($Source))
try {
    if($bitmap.Width -ne 16 -or $bitmap.Height -ne 24){throw 'Expected the supplied16x24 reference; never resize it.'}
    $lines=[Collections.Generic.List[string]]::new()
    $lines.Add('/* Generated by scripts/import-classic-time-strike.ps1 from the supplied PNG.')
    $lines.Add(' * Original pixel layout/RGB555; bit15 marks transparency. Do not resize. */')
    $lines.Add('static const uint16_t classic_time_strike_rgb555[24][16]={')
    for($y=0;$y -lt 24;++$y){
        $row=for($x=0;$x -lt 16;++$x){
            $c=$bitmap.GetPixel($x,$y)
            if($c.A -ne 0 -and $c.A -ne 255){throw 'Unexpected partial alpha.'}
            $value=if(!$c.A){0x8000}else{([int]$c.R -shr 3) -bor (([int]$c.G -shr 3) -shl 5) -bor (([int]$c.B -shr 3) -shl 10)}
            '0x{0:x4}' -f $value
        }
        $lines.Add('    {'+($row -join ',')+'}'+$(if($y -lt 23){','}else{''}))
    }
    $lines.Add('};')
    $destination=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../src/classic_time_strike.inc'))
    [IO.File]::WriteAllText($destination,($lines -join "`n")+"`n",[Text.UTF8Encoding]::new($false))
} finally {$bitmap.Dispose()}
