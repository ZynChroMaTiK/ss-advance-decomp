"""Bake small palette-only water ripples; all shape math is offline."""
from math import atan2, cos, hypot, pi, sin
from pathlib import Path
from random import Random

ROOT = Path(__file__).resolve().parents[1]
VARIANTS, FRAMES, SIZE = 8, 12, 24


def bake(variant, frame):
    rows, surface = [0] * SIZE, [0] * SIZE
    if frame in (0, FRAMES-1):
        return rows, surface
    rng = Random(0x57415445 + variant)
    offset, bend, stretch, breakup = [rng.uniform(-1, 1) for _ in range(4)]
    t = frame / (FRAMES-1)
    life = min(1, t*4) * min(1, (1-t)*3)
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = x-11.5, y-11.5
            kind = 0
            if variant < 4:
                # Expanding irregular rings, with a weaker delayed inner echo.
                # Broad coherent gaps replace random pixel holes and speckles.
                angle = atan2(dy, dx)
                radius = hypot(dx, dy*(1.05+.12*stretch))
                shape = .4*sin(3*angle+offset*pi)+.22*cos(5*angle+bend)
                crest = 1.4+9.2*t+shape
                arcs = .6*sin(2*angle+offset*pi)+.4*cos(3*angle+breakup)
                for echo in range(2):
                    r = crest-3.0*echo
                    if r < 1.5:
                        continue
                    width = (.78-.22*echo)*(.65+.35*life)
                    if abs(radius-r) < width and arcs > .85-(1.55-.3*echo)*life:
                        kind = 2 if radius <= r else 3
            else:
                # Short wind ripples: tapered, bent parallel wavelets with
                # unequal lengths and spacing. The packet drifts then dissolves.
                for echo in range(3):
                    length = (8.8-echo*1.3+stretch)*life
                    if abs(dx) >= length:
                        continue
                    arc = .025*dx*dx*(1+.6*bend)+.35*sin(dx*.55+offset)
                    crest = -4.0+echo*(2.6+.25*breakup)+3.5*t+arc
                    taper = 1-(abs(dx)/length)**3
                    width = (.68+.12*sin(dx*.4+echo))*taper
                    if abs(dy-crest) < width and cos(dx*.45+offset+echo) > .65-1.6*life:
                        kind = 2 if dy <= crest else 3
            if kind == 2:
                rows[y] |= 1 << x
            elif kind == 3:
                surface[y] |= 1 << x
    return rows, surface


def main():
    text = '/* Generated by scripts/build-water-ripples.py. Light/base water crests; 18 KiB ROM. */\n'
    text += f'enum {{ WATER_RIPPLE_VARIANTS={VARIANTS}, WATER_RIPPLE_FRAMES={FRAMES}, WATER_RIPPLE_SIZE={SIZE} }};\n'
    atlas = [[bake(v, f) for f in range(FRAMES)] for v in range(VARIANTS)]
    for layer, name in enumerate(('water_ripples', 'water_ripples_surface')):
        text += f'static const uint32_t {name}[WATER_RIPPLE_VARIANTS][WATER_RIPPLE_FRAMES][WATER_RIPPLE_SIZE]={{\n'
        for variant in atlas:
            text += '  {\n'
            for frame in variant:
                text += '    {' + ','.join(f'UINT32_C(0x{v:08x})' for v in frame[layer]) + '},\n'
            text += '  },\n'
        text += '};\n'
    (ROOT / 'src/water_ripples.inc').write_text(text, encoding='ascii')


if __name__ == '__main__':
    main()
