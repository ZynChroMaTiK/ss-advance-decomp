param([string]$Source=(Join-Path $PSScriptRoot '../assets/classic-hud/tommygun-ammo.png'))
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Drawing
$rom=[IO.File]::ReadAllBytes((Join-Path $PSScriptRoot '../orig/SSA.gba'))
$palette=@{}
for($i=1;$i -lt 256;++$i){
    $c=[BitConverter]::ToUInt16($rom,0x79effc+2*$i)
    $r=$c-band31;$g=($c-shr5)-band31;$b=($c-shr10)-band31
    $color=[Drawing.Color]::FromArgb(255,(($r-shl3)-bor($r-shr2)),(($g-shl3)-bor($g-shr2)),(($b-shl3)-bor($b-shr2))).ToArgb()
    if(-not $palette.ContainsKey($color)){$palette[$color]=$i}
}
$bitmap=[Drawing.Bitmap]::FromFile([IO.Path]::GetFullPath($Source))
try {
    if($bitmap.Width -ne 16 -or $bitmap.Height -ne 16){throw 'Expected16x16 sprite; never resize it.'}
    $lines=[Collections.Generic.List[string]]::new()
    $lines.Add('/* Generated by scripts/import-classic-tommy-ammo.ps1 from the supplied PNG.')
    $lines.Add(' * Exact16x16 layout/OBJ palette; index0 is transparent. Do not resize. */')
    $lines.Add('static const uint8_t classic_tommy_ammo_indices[16][16]={')
    for($y=0;$y -lt 16;++$y){
        $row=for($x=0;$x -lt 16;++$x){
            $c=$bitmap.GetPixel($x,$y)
            if($c.A -ne 0 -and $c.A -ne 255){throw "Partial alpha at$x,$y; expected transparent or opaque pixels."}
            $index=0
            if($c.A){
                if(-not $palette.ContainsKey($c.ToArgb())){throw "Color outside the ROM OBJ palette at$x,$y; do not silently recolor artwork."}
                $index=$palette[$c.ToArgb()]
            }
            '0x{0:x2}' -f $index
        }
        $lines.Add('    {'+($row -join ',')+'}'+$(if($y -lt 15){','}else{''}))
    }
    $lines.Add('};')
    $destination=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../src/classic_tommy_ammo.inc'))
    [IO.File]::WriteAllText($destination,($lines -join "`n")+"`n",[Text.UTF8Encoding]::new($false))
} finally {$bitmap.Dispose()}
