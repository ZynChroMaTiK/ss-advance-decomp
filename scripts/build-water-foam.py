"""Bake outward water: transparent, white, lighter water, base water.

All shape/animation math runs offline. Two one-bit planes occupy 128 KiB in ROM;
runtime only selects a frame/variant and tests two bits. Original palette inks.
"""
from pathlib import Path
from math import sin, pi
from random import Random

ROOT = Path(__file__).resolve().parents[1]
VARIANTS = 16
FRAMES = 32
WIDTH = 64


def bake(variant, phase):
    rng = Random(0x535341 + variant)
    bend, lobe, drift, width = [rng.uniform(-1, 1) for _ in range(4)]
    foam, wash = [0] * 32, [0] * 32
    time = 2 * pi * phase / FRAMES
    t = phase / (FRAMES-1)
    # A quiet start/end hides the reset. Dissolution removes coherent patches
    # at their current position; it never reverses the crest's motion.
    birth = min(1, t/.16)
    fade = max(0, min(1, (.90-t)/.48))
    life = birth*birth*(3-2*birth) * fade*fade*(3-2*fade)
    family = variant % 4
    for x in range(WIDTH):
        # Every variant shares its end columns, including the animation phase.
        # Broad interior changes avoid both visible tile joins and fine noise.
        a = 2 * pi * x / (WIDTH-1)
        interior = sin(pi * x / (WIDTH-1)) ** 2
        curve = .45*sin(a+.45) + interior*(bend*1.4 + .65*sin((family+1)*a+drift))
        crest = 2.0 + 11.0*t*(2-t) + curve
        # The attached border uses only the water's base/light inks.
        # White highlights are reserved for the separate traveling wave.
        bank = 1.0 + .4*sin(a + .2*sin(time)) + .3*interior*width
        arcs = (.65*sin(a+.4+interior*lobe*2.5)
                + .35*sin(2*a-1+interior*bend*2)
                + interior*.3*sin((family+1)*a+drift*2))
        bank_light = arcs > .78 and sin(time) > .3
        foam_on = life > .05 and arcs > 1.15-1.35*life
        wash_on = life > .05 and arcs > 1.15-2.5*life
        behind = (.9 + .5*interior*(width+1))*life
        row_word, bit = x >> 5, 1 << (x & 31)
        for y in range(16):
            delta = y - crest
            kind = 0
            if y <= bank or (wash_on and -behind <= delta <= .45):
                # Lighter leading face; original water on the trailing lip
                # gives depth over reflections without a dark offset shadow.
                kind = 3 if y > bank and delta < -.65 else 2
            if y == int(crest+.5) and foam_on:
                kind = 1 if arcs > .65 else 2
            if y <= bank:
                kind = 2 if y == int(bank) or bank_light else 3
            if kind & 1:
                foam[y*2+row_word] |= bit
            if kind & 2:
                wash[y*2+row_word] |= bit
    # Floating point sin(2*pi) must never select a different endpoint pixel.
    for plane in (foam, wash):
        for y in range(16):
            plane[y*2+1] = (plane[y*2+1] & 0x7fffffff) | ((plane[y*2] & 1) << 31)
    return foam, wash


def main():
    atlas = [[bake(v, f) for f in range(FRAMES)] for v in range(VARIANTS)]
    text = '/* Generated by scripts/build-water-foam.py. 128 KiB ROM; low/high ink bits: clear/white/light/base. */\n'
    text += f'enum {{ WATER_FOAM_VARIANTS={VARIANTS}, WATER_FOAM_WIDTH={WIDTH} }};\n'
    for layer, name in enumerate(('water_foam', 'water_foam_surface')):
        text += f'static const uint32_t {name}[WATER_FOAM_VARIANTS][32][32]={{\n'
        for variant in atlas:
            text += '  {\n'
            for frame in variant:
                text += '    {\n'
                for start in range(0, 32, 4):
                    text += '        ' + ','.join(f'UINT32_C(0x{v:08x})' for v in frame[layer][start:start+4]) + ',\n'
                text += '    },\n'
            text += '  },\n'
        text += '};\n'
    (ROOT / 'src/water_foam.inc').write_text(text, encoding='ascii')


if __name__ == '__main__':
    main()
